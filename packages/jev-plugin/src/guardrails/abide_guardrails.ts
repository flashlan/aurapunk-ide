/**
 * Abide Rule Guardrails System
 *
 * Enforces AGENTS.md and repository rules on every edit/diff using:
 * 1. RLCD deterministic checks (<1ms, local CPU, 0 tokens, AST/regex)
 * 2. Fast Jev System-2 Decision Classifier (~300ms, calibrated probability via the TypeSafe API)
 * 3. Adaptive Router with Graceful Fallback (Laya -> Jev -> Laya)
 */

import { JevClassifier } from "../classifiers/jev_classifier.js";
import type { DecisionClassifier } from "../classifiers/interface.js";
import type { TypedQuestion } from "../types.js";

export interface AbideRule {
  id: string;
  name: string;
  source: string; // e.g., "AGENTS.md line 145"
  instruction: string;
  when: "edit" | "turn";
  threshold: number; // 0.0 to 1.0 (default 0.70)
  // Deterministic checks executed by Laya in <1ms
  layaCheck?: {
    forbiddenFiles?: string[];
    forbiddenRegex?: RegExp[];
    requiredPatterns?: RegExp[];
  };
}

export interface RuleViolation {
  ruleId: string;
  ruleName: string;
  source: string;
  probability: number;
  message: string;
  repairInstruction: string;
  evaluator: "laya" | "jev";
}

export interface RuleEvaluationResult {
  allowed: boolean;
  violations: RuleViolation[];
  latencyMs: number;
  evaluatorUsed: "laya" | "jev" | "adaptive";
  /**
   * True when the semantic (Jev) pass was requested but could not run or could
   * not answer every rule — a missing key, a timeout, a network/API error, or
   * unusable answers. `allowed` then reflects the DETERMINISTIC checks only, so
   * a caller must report it as "not fully verified" instead of a clean pass.
   *
   * Guardrail semantics are unchanged: a Jev outage still never blocks the
   * agent. Only the reporting changes.
   */
  degraded?: boolean;
  /** Why the semantic pass was incomplete, when `degraded` is set. */
  degradationReason?: string;
  /** Semantic rules that were requested but produced no usable answer. */
  unevaluatedRuleIds?: string[];
}

